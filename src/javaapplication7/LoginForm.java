   private int attemptCount = 0;
   private final int MAX_ATTEMPTS = 3;
   private void performLogin() {
    String username = usernameField.getText();
    String password = new String(passwordField.getPassword());

    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3307/project database", "root", "");
        String sql = "SELECT * FROM userdatabase WHERE username = ? AND password = ?";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, username);
        ps.setString(2, password);
        ResultSet rs = ps.executeQuery();

        if (rs.next()) {
            JOptionPane.showMessageDialog(this, "Login successful!");

            DashBoard dashboard = new DashBoard();
            dashboard.setVisible(true);
            dashboard.setLocationRelativeTo(null);
            this.dispose();
        } else {
            attemptCount++;
            if (attemptCount >= MAX_ATTEMPTS) {
                JOptionPane.showMessageDialog(this, "Maximum login attempts exceeded. Program will now close.");
                System.exit(0);
            } else {
                JOptionPane.showMessageDialog(this, "Invalid username or password. Attempt " + attemptCount + " of " + MAX_ATTEMPTS, "Login Failed", JOptionPane.ERROR_MESSAGE);
            }
        }

        rs.close();
        ps.close();
        conn.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
}


