    public void showEmployeeStatusChart() {
    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3307/employee_db", "root", "");

        int activeCount = 0;
        int inactiveCount = 0;
        int totalCount = 0;

        
        PreparedStatement pstActive = conn.prepareStatement("SELECT COUNT(*) FROM employees WHERE status = 'Active'");
        ResultSet rsActive = pstActive.executeQuery();
        if (rsActive.next()) activeCount = rsActive.getInt(1);

        
        PreparedStatement pstInactive = conn.prepareStatement("SELECT COUNT(*) FROM employees WHERE status = 'Inactive'");
        ResultSet rsInactive = pstInactive.executeQuery();
        if (rsInactive.next()) inactiveCount = rsInactive.getInt(1);

       
        totalCount = activeCount + inactiveCount;

        
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();
        dataset.addValue(activeCount, "Employees", "Active");
        dataset.addValue(inactiveCount, "Employees", "Inactive");
        dataset.addValue(totalCount, "Employees", "Total");

       
        JFreeChart barChart = ChartFactory.createBarChart(
                "", // Title
                "Status", 
                "", 
                dataset);

        
        ChartPanel chartPanel = new ChartPanel(barChart);
        chartPanel.setPreferredSize(new java.awt.Dimension(850, 450));

       
        jPanelChart.setLayout(new java.awt.BorderLayout());
        jPanelChart.removeAll(); 
        jPanelChart.add(chartPanel, java.awt.BorderLayout.CENTER);
        jPanelChart.validate();
        jPanelChart.repaint();

        conn.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}

    
    
    public void loadTable() {
    
        try {
             Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3307/employee_db", "root", "");
             String sql = "SELECT * FROM employees";
             PreparedStatement pst = con.prepareStatement(sql);
             ResultSet rs = pst.executeQuery();

                 DefaultTableModel model1 = (DefaultTableModel) jTable2.getModel(); 
                 DefaultTableModel model2 = (DefaultTableModel) Table2.getModel();
                 model1.setRowCount(0); 
                 model2.setRowCount(0); 

                     while (rs.next()) {
                        String id = rs.getString("id");
                        String name = rs.getString("employee_name");
                        String position = rs.getString("position");
                        String email = rs.getString("email");
                        String status = rs.getString("status");

                           model1.addRow(new Object[]{id, name, position, email, status});
                           model2.addRow(new Object[]{id, name, position, email, status});
                 }
                con.close();
            } catch (Exception ex) {
                             JOptionPane.showMessageDialog(null, "Error loading table: " + ex.getMessage());
    }
}

